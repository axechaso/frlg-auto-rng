from dataclasses import dataclass

GUIDE_VERSION = 1


@dataclass(frozen=True)
class GuideStep:
    step_id: str
    title: str
    body: str
    anchor_id: str
    visible_when: str = ""
    completion_check: str = ""
    risk_note: str = ""


def steps(*rows):
    return tuple(GuideStep(*row) for row in rows)


